export function getRelatedResources(
  resource,
  allResources = RESOURCES,
  limit = 3,
) {
  if (!resource) return [];
  const tags = new Set(resource.tags || []);

  return allResources
    .filter((r) => r.name !== resource.name)
    .map((r) => {
      let commonScore = 0;
      if (r.category === resource.category) commonScore += 2;
      r.tags?.forEach((t) => {
        if (tags.has(t)) commonScore += 1;
      });
      return { resource: r, score: commonScore };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.resource);
}
